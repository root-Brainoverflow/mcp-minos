const DEFAULT_LANG = "en";

function _read() {
  try {
    const v = localStorage.getItem("minos_lang");
    return v === "ko" || v === "en" ? v : DEFAULT_LANG;
  } catch {
    return DEFAULT_LANG;
  }
}

let _lang = _read();

export function getLang() {
  return _lang;
}

export function setLang(l) {
  _lang = l === "ko" ? "ko" : "en";
  try { localStorage.setItem("minos_lang", _lang); } catch { /* ignore */ }
}

export function t(key, vars) {
  const table = STRINGS[_lang] || STRINGS.en;
  let s = table[key];
  if (s == null) s = STRINGS.en[key];
  if (s == null) s = key;
  if (vars) {
    for (const k of Object.keys(vars)) {
      s = s.replace(new RegExp(`\\{${k}\\}`, "g"), String(vars[k]));
    }
  }
  return s;
}
